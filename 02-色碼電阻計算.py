"""依照四環或五環電阻色碼計算阻值。"""

from decimal import Decimal


數字色碼 = {
    "黑": 0, "棕": 1, "紅": 2, "橙": 3, "黃": 4,
    "綠": 5, "藍": 6, "紫": 7, "灰": 8, "白": 9,
}
顏色編號 = {顏色: str(數字) for 顏色, 數字 in 數字色碼.items()}
顏色編號.update({"金": "10", "銀": "11"})
倍率色碼 = {顏色: Decimal(10) ** 數字 for 顏色, 數字 in 數字色碼.items()}
倍率色碼.update({"金": Decimal("0.1"), "銀": Decimal("0.01")})
誤差色碼 = {
    "棕": "1", "紅": "2", "綠": "0.5", "藍": "0.25",
    "紫": "0.1", "灰": "0.05", "金": "5", "銀": "10",
}


def 輸入顏色(提示: str, 可用顏色: dict) -> str:
    編號選項 = {顏色編號[顏色]: 顏色 for 顏色 in 可用顏色}
    選項文字 = "、".join(f"{編號}：{顏色}" for 編號, 顏色 in 編號選項.items())
    while True:
        編號 = input(f"{提示}（{選項文字}）：").strip()
        if 編號 in 編號選項:
            return 編號選項[編號]
        print("編號無效，請從括號內的編號中選擇。")


def 主程式() -> None:
    print("色碼電阻計算器（四環／五環）")
    print("請從距離電阻一端較近的色環開始輸入。")

    while True:
        環數 = input("請輸入色環數（4 或 5）：").strip()
        if 環數 in ("4", "5"):
            break
        print("請輸入 4 或 5。")

    有效數字 = 0
    for 環 in range(1, int(環數) - 1):
        可用顏色 = 數字色碼 if 環 > 1 else {
            顏色: 數字 for 顏色, 數字 in 數字色碼.items() if 數字 != 0
        }
        顏色 = 輸入顏色(f"第 {環} 環（有效數字）", 可用顏色)
        有效數字 = 有效數字 * 10 + 數字色碼[顏色]

    倍率顏色 = 輸入顏色("倍率環", 倍率色碼)
    誤差顏色 = 輸入顏色("誤差環", 誤差色碼)
    阻值 = 有效數字 * 倍率色碼[倍率顏色]

    if 阻值 >= 1_000_000:
        顯示阻值 = f"{阻值 / 1_000_000:g} MΩ"
    elif 阻值 >= 1_000:
        顯示阻值 = f"{阻值 / 1_000:g} kΩ"
    else:
        顯示阻值 = f"{阻值:g} Ω"

    print(f"電阻值：{顯示阻值} ±{誤差色碼[誤差顏色]}%")


if __name__ == "__main__":
    主程式()